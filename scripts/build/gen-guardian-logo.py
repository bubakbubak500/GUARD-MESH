"""Render the original Guardian shield for early boot and LVGL. Requires PySide6."""
from pathlib import Path
from PySide6.QtCore import Qt
from PySide6.QtGui import QImage, QPainter
from PySide6.QtSvg import QSvgRenderer
ROOT = Path(__file__).resolve().parents[2]
SIZE = 144

def main():
    renderer = QSvgRenderer(str(ROOT / 'assets/guardian-shield.svg'))
    if not renderer.isValid(): raise RuntimeError('Invalid Guardian SVG')
    high = QImage(SIZE * 4, SIZE * 4, QImage.Format_ARGB32)
    high.fill(Qt.transparent)
    painter = QPainter(high)
    renderer.render(painter)
    painter.end()
    image = high.scaled(SIZE, SIZE, Qt.IgnoreAspectRatio, Qt.SmoothTransformation)
    rgb, alpha = [], []
    for y in range(SIZE):
        for x in range(SIZE):
            c = image.pixelColor(x, y)
            r,g,b,a = c.red(),c.green(),c.blue(),c.alpha()
            pixel = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
            alpha.extend([pixel & 255, pixel >> 8, a])
            r,g,b = r*a//255,g*a//255,b*a//255
            rgb.append(((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3))
    header = '''// Generated by scripts/build/gen-guardian-logo.py; source: assets/guardian-shield.svg
#pragma once
#include <stdint.h>
#define GUARDIAN_LOGO_W 144
#define GUARDIAN_LOGO_H 144
#ifdef __cplusplus
extern "C" {
#endif
extern const uint16_t GUARDIAN_LOGO_RGB565[144 * 144];
extern const uint8_t GUARDIAN_LOGO_ALPHA[144 * 144 * 3];
#ifdef __cplusplus
}
#endif
'''
    (ROOT/'src/guardian_logo.h').write_text(header,encoding='utf-8')
    lines=['// Generated by scripts/build/gen-guardian-logo.py; do not edit.','#include "guardian_logo.h"']
    for name,kind,items in [('RGB565','uint16_t',rgb),('ALPHA','uint8_t',alpha)]:
        lines.append(f'const {kind} GUARDIAN_LOGO_{name}[] = {{')
        lines.extend('  '+','.join(hex(v) for v in items[i:i+24])+',' for i in range(0,len(items),24))
        lines.append('};')
    (ROOT/'src/guardian_logo.c').write_text('\n'.join(lines)+'\n',encoding='utf-8')

if __name__ == '__main__': main()
